"""Build the embedded proportional serif font used by AfterMe PDFs.

Requires fontTools. The generated JavaScript module is checked in so normal
development, tests, and Worker deployment use the included generated font assets.
"""

from __future__ import annotations

import argparse
import base64
import io
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont


RANGES = (
    (0x0020, 0x007E),  # Basic Latin
    (0x00A0, 0x024F),  # Latin supplements and extensions
    (0x02B0, 0x036F),  # Spacing modifiers and combining marks
    (0x0370, 0x03FF),  # Greek
    (0x0400, 0x052F),  # Cyrillic
    (0x2000, 0x206F),  # General punctuation
    (0x20A0, 0x20CF),  # Currency symbols
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--source",
        type=Path,
        required=True,
        help="Path to the OFL-licensed Noto Serif SC variable font",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "src" / "pdf-serif-font-data.js",
    )
    return parser.parse_args()


def rename_font(font: TTFont) -> None:
    replacements = {
        1: "AfterMe PDF Serif",
        2: "Regular",
        3: "AfterMe PDF Serif Regular 1.0",
        4: "AfterMe PDF Serif Regular",
        6: "AfterMePDFSerif",
    }
    name_table = font["name"]
    for record in name_table.names:
        if record.nameID not in replacements:
            continue
        value = replacements[record.nameID]
        record.string = value.encode(record.getEncoding(), errors="replace")


def make_font(source: Path) -> bytes:
    font = TTFont(source)
    if "fvar" in font:
        font = instantiateVariableFont(font, {"wght": 400}, inplace=False)

    options = subset.Options()
    options.layout_features = []
    options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]
    options.name_languages = [0x0409]
    options.glyph_names = False
    options.recalc_timestamp = False
    options.drop_tables += ["DSIG"]

    codepoints = set()
    for start, end in RANGES:
        codepoints.update(range(start, end + 1))
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=codepoints)
    subsetter.subset(font)
    rename_font(font)

    buffer = io.BytesIO()
    font.flavor = None
    font.save(buffer, reorderTables=True)
    return buffer.getvalue()


def javascript_module(font_bytes: bytes) -> str:
    font = TTFont(io.BytesIO(font_bytes))
    cmap = font.getBestCmap()
    glyph_ids = {name: index for index, name in enumerate(font.getGlyphOrder())}
    hmtx = font["hmtx"].metrics
    codepoints = sorted(cmap)
    gids = [glyph_ids[cmap[point]] for point in codepoints]
    widths = [hmtx[cmap[point]][0] for point in codepoints]
    head = font["head"]
    hhea = font["hhea"]
    os2 = font["OS/2"]
    post = font["post"]
    cap_height = getattr(os2, "sCapHeight", hhea.ascent)

    encoded = base64.b64encode(font_bytes).decode("ascii")
    chunks = [encoded[index:index + 100] for index in range(0, len(encoded), 100)]
    chunk_source = "\n".join(f'  "{chunk}",' for chunk in chunks)

    return f'''// SPDX-License-Identifier: OFL-1.1
// Generated by scripts/build-pdf-serif-font.py. Do not edit by hand.
// Derived from Noto Serif SC under the SIL Open Font License 1.1.
const BASE64_CHUNKS = [
{chunk_source}
];

export const PDF_SERIF_FONT_BASE64 = BASE64_CHUNKS.join("");
export const PDF_SERIF_FONT_META = Object.freeze({{
  postscriptName: "AfterMePDFSerif",
  unitsPerEm: {head.unitsPerEm},
  bbox: Object.freeze([{head.xMin}, {head.yMin}, {head.xMax}, {head.yMax}]),
  ascent: {hhea.ascent},
  descent: {hhea.descent},
  capHeight: {cap_height},
  italicAngle: {post.italicAngle},
}});
export const PDF_SERIF_CODEPOINTS = Object.freeze({codepoints});
export const PDF_SERIF_GLYPH_IDS = Object.freeze({gids});
export const PDF_SERIF_ADVANCES = Object.freeze({widths});
'''


def main() -> None:
    args = parse_args()
    font_bytes = make_font(args.source)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(javascript_module(font_bytes), encoding="utf-8", newline="\n")
    print(f"wrote {args.output} ({len(font_bytes)} embedded font bytes)")


if __name__ == "__main__":
    main()
